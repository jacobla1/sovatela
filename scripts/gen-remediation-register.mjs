#!/usr/bin/env node
// Generate docs/release/REMEDIATION-REGISTER.md.
//
// The register must name the code commit it describes, and it cannot name the
// commit that contains itself — writing the file changes the tree, so any hash
// embedded in it is stale the moment it is committed. The previous version
// named a commit two behind and nobody noticed, because the test only checked
// that *some* seven-character hash was present.
//
// So the flow is deliberate: freeze the code, then run this, then commit the
// register on its own. It names HEAD by default, which at that point is the
// frozen code commit, and the register lands in the commit after it.
//
//     node scripts/gen-remediation-register.mjs            # names HEAD
//     node scripts/gen-remediation-register.mjs <commit>   # names a given one
//
// `tests/docPromises.test.js` checks the named commit exists, is an ancestor of
// HEAD, and is not HEAD itself.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repo = resolve(import.meta.dirname, "..");
const git = (...a) => execFileSync("git", a, { cwd: repo, encoding: "utf8" }).trim();

const target = process.argv[2] || "HEAD";
const commit = git("rev-parse", "--short", target);
const rows = JSON.parse(readFileSync(join(repo, "scripts/remediation-rows.json"), "utf8"));

const doc = `# Remediation register — August 2026 external review

Generated: ${new Date().toISOString().slice(0, 10)} · Code commit described: \`${commit}\`
· Public release under review: **v1.6.0** (\`4f7e17b\`, unchanged)

Generated by \`scripts/gen-remediation-register.mjs\`. Do not edit by hand — a
hand-edited register drifts from the code it describes, which is how an earlier
revision came to name a commit two behind while still claiming F17 had no hash
verification.

The commit above is the **code** commit this describes. This file is committed
after it, on its own, because a register cannot name the commit that contains it.

This lives in version control rather than as an exported file. The revision
before it was shared as an HTML export, was not regenerated when its contents
changed, and was reviewed in a stale state — which cost a full review round
arguing against claims that had already been withdrawn.

**Read the two status columns separately.** *Public v1.6.0* is what a person can
download today. *Candidate* is what is on this branch. They are different, and
conflating them is how this register once asserted a protection that did not
exist: an earlier revision said v1.6.0 had withdrawn terminal access. It had not
— that was written after the release, in an uncommitted working copy that was
discarded.

| # | Finding | Public v1.6.0 | Candidate | Residual risk | Evidence | Independently re-verified |
|---|---|---|---|---|---|---|
${rows.map((r) => `| \`${r[0]}\` | ${r.slice(1).join(" | ")} |`).join("\n")}

## Standing facts

- **Every defect above is present in the public v1.6.0 release.** Nothing on this
  branch has been released.
- **The affected population is unknown.** The application has no telemetry, so
  there is no way to establish who installed terminal access. There is **no known
  exploitation**, which is not the same as no exploitation.
- The corrected security note is
  [\`SECURITY-NOTE-2026-08-30-claude-glm.md\`](SECURITY-NOTE-2026-08-30-claude-glm.md).
  **It is not yet published, and no GHSA has been filed.**
- Accepted risks are recorded with their trade in
  [\`TECHNICAL-SPEC.md\` § 7.2](../TECHNICAL-SPEC.md#72-accepted-risks-from-the-august-2026-review).
`;

writeFileSync(join(repo, "docs/release/REMEDIATION-REGISTER.md"), doc);
console.log(`Wrote the register for code commit ${commit} (${rows.length} findings)`);
